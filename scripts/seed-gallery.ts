/**
 * Gallery v2.0 Seed & Readiness Verification Script
 *
 * Seeds the in-memory / runtime Gallery v2.0 context with:
 * - 36 CatalogEntry definitions
 * - 6 Multi-agent Bundles
 * - 12 compiled PilotPacks + ReleaseManifests
 * - 36 BenchmarkTasks
 * - Public CreatorProfiles, GalleryListings, and ServiceOfferings
 */

import * as fs from "fs";
import * as path from "path";
import { loadGalleryCatalog } from "@cognitive-forge/domain-packs";
import { createFreshV1Context } from "../apps/web/lib/api/v1-runtime";

function main(): void {
  const loadedCatalog = loadGalleryCatalog();
  const embeddedPath = path.resolve(
    process.cwd(),
    "packages/domain-packs/src/gallery/embedded-catalog.ts"
  );
  const embeddedSource = `/**
 * Auto-generated embedded Gallery v2.0 catalog fallback for serverless runtimes (e.g. Vercel).
 * Generated by scripts/seed-gallery.ts from docs/Cognitive_Forge_OS_Gallery_Repo_Docs_v2_0/gallery.
 */
import type { LoadedGalleryCatalog } from "./catalog-loader";

export const EMBEDDED_GALLERY_CATALOG: LoadedGalleryCatalog = ${JSON.stringify(loadedCatalog, null, 2)} as unknown as LoadedGalleryCatalog;
`;
  fs.writeFileSync(embeddedPath, embeddedSource, "utf8");

  const ctx = createFreshV1Context();

  const publicListings = ctx.galleryService.listPublicListings({ limit: 100 });
  const runnableListings = ctx.galleryService.listPublicListings({
    limit: 100,
    availability: "published_runnable",
  });
  const previewListings = ctx.galleryService.listPublicListings({
    limit: 100,
    availability: "preview_only",
  });

  console.log(
    JSON.stringify(
      {
        status: "SEEDED",
        catalog_entries: ctx.galleryService.catalogEntries.size,
        pilot_packs: ctx.galleryService.pilotPacks.size,
        benchmark_tasks: ctx.galleryService.benchmarkTasks.size,
        bundles: ctx.galleryService.bundles.length,
        creators_total: ctx.galleryService.creators.size,
        public_listings_total: publicListings.items.length,
        published_runnable_listings: runnableListings.items.length,
        preview_only_listings: previewListings.items.length,
        compiled_releases: ctx.coreStore.releases.size,
      },
      null,
      2
    )
  );
}

main();
